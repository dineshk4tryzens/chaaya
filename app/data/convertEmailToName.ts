function capitalizeFirstLetter([first = '', ...rest]: string[]): string {
  return [first?.toUpperCase(), ...rest]?.join('');
}

export function getNameFromEmail(email?: string) {
  const splittedData = email?.split('.') || []
  if (splittedData.length <= 0) throw new Error('Email parsing error');
  const fname: unknown = splittedData[0]
  const sname: unknown = splittedData[1]?.split('@')[0]
  if (!sname) return;
  return `${capitalizeFirstLetter(fname as string[])} ${capitalizeFirstLetter(sname as string[])}`
}

